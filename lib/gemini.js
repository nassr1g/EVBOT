const refusalCache = new Map() // key: `${chatId}:${reasonKey}` → { text, expiresAt }

function getCachedRefusal(chatId, reasonKey) {
  const key = `${chatId}:${reasonKey}`
  const entry = refusalCache.get(key)
  if (!entry) return null
  if (Date.now() > entry.expiresAt) {
    refusalCache.delete(key)
    return null
  }
  return entry.text
}

function setCachedRefusal(chatId, reasonKey, text) {
  refusalCache.set(`${chatId}:${reasonKey}`, {
    text,
    expiresAt: Date.now() + REFUSAL_CACHE_TTL_MS,
  })
}

