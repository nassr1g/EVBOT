// ─────────────────────────────────────────────
//  استعلام رصيد Tavily الحقيقي — بعكس Gemini وSerper، توفر Tavily فعلياً endpoint حياً
//  ورسمياً لهذا الغرض (GET /usage)، موثّق من Tavily نفسها. هذا استدعاء شبكة إضافي منفصل
//  تماماً عن /search، ولا يُحتسب من حصة البحث نفسها (Tavily توثّق أنه غير مُكلِّف رصيداً).
//  نستخدم هذا كمصدر أساسي حقيقي لأمر "حالة التوكنز"، مع التراجع للعداد المحلي التقديري
//  فقط لو فشل هذا الاستدعاء (مشكلة شبكة، أو مفتاح لا يدعم هذا الـendpoint تحديداً)
// ─────────────────────────────────────────────

async function fetchTavilyRealUsage() {
  if (!TAVILY_API_KEY) return null

  try {
    const res = await fetch('https://api.tavily.com/usage', {
      method: 'GET',
      headers: { 'Authorization': `Bearer ${TAVILY_API_KEY}` },
    })

    if (!res.ok) {
      console.error(`⚠️ فشل جلب رصيد Tavily الحقيقي (HTTP ${res.status}) — سنعرض التقدير المحلي بدلاً منه`)
      return null
    }

    const data = await res.json()
    // نفضّل بيانات المفتاح نفسه (key.usage/key.limit) لأنها أدق تمثيل لحصة هذا المفتاح
    // بالذات؛ account.plan_usage/plan_limit تمثل كامل الحساب (قد يشمل مفاتيح أخرى)
    const used = Number(data?.key?.usage)
    const limit = Number(data?.key?.limit)

    if (!Number.isFinite(used) || !Number.isFinite(limit) || limit <= 0) {
      console.error('⚠️ استجابة رصيد Tavily بصيغة غير متوقعة — سنعرض التقدير المحلي بدلاً منه')
      return null
    }

    const percentUsed = Math.min(100, Math.round((used / limit) * 100))
    return {
      available: true,
      used,
      cap: limit,
      percentUsed,
      percentLeft: Math.max(0, 100 - percentUsed),
      isLive: true, // علامة تُستخدم بالعرض لتمييزه عن التقدير المحلي لباقي الخدمات
    }
  } catch (err) {
    console.error('❌ فشل الاتصال بـ /usage الخاص بـ Tavily:', err?.message || String(err))
    return null
  }
}

// ─────────────────────────────────────────────
//  بحث ويب فعلي عبر Tavily — خدمة مستقلة تماماً عن Gemini/Google، لها حصتها
//  الخاصة (مجانية حتى 1000 بحث شهرياً)، فلا تتأثر بأي استنفاد لحصة Gemini
// ─────────────────────────────────────────────

async function performWebSearch(query) {
  if (!TAVILY_API_KEY) {
    console.error('⚠️ TAVILY_API_KEY غير موجود — تعذر تنفيذ البحث')
    return null
  }

  try {
    const res = await fetch('https://api.tavily.com/search', {
      method: 'POST',
      headers: {
        'Authorization': `Bearer ${TAVILY_API_KEY}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        query,
        search_depth: 'basic',
        max_results: 4,
        include_answer: true,
      }),
    })

    if (!res.ok) {
      const errText = await res.text().catch(() => '')
      if (res.status === 401 || res.status === 403) {
        console.error(`⚠️ خطأ ${res.status} من Tavily — عادة يعني مشكلة بصلاحية المفتاح نفسه (مفتاح غير مفعّل بالكامل، أو نوعه لا يدعم هذا الاستخدام)، وليس مشكلة بصياغة الطلب أو الاتصال بالشبكة`)
      }
      throw new Error(`Tavily HTTP ${res.status}: ${errText.slice(0, 300)}`)
    }

    // الطلب نجح فعلياً هنا (res.ok) — هذا يعني أن Tavily احتسبته من الحصة الشهرية بغض
    // النظر عن محتوى النتيجة نفسها، فنسجله الآن قبل أي معالجة إضافية للبيانات
    usageTracker.recordUsage('tavily')

    const data = await res.json()

    // Tavily توفر إجابة موجزة جاهزة (include_answer) أحياناً، وهي الأفضل لو وُجدت
    if (data.answer) {
      return data.answer
    }

    // إذا ما وُجدت إجابة موجزة، نبني سياقاً من أهم النتائج الخام
    const results = Array.isArray(data.results) ? data.results.slice(0, 3) : []
    if (results.length === 0) {
      return null
    }

    return results
      .map(r => `${r.title || ''}: ${(r.content || '').slice(0, 300)}`)
      .join('\n')
  } catch (err) {
    console.error('❌ فشل البحث عبر Tavily:', err?.message || String(err))
    return null
  }
}

