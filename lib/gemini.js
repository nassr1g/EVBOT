async function getUsageReport() {
  const localEstimate = usageTracker.getUsageSummary({
    hasGemini: !!GEMINI_KEY,
    hasTavily: !!TAVILY_API_KEY,
    hasSerper: !!SERPER_API_KEY,
  })

  // Gemini وSerper: لا يوجد لهما مصدر حي فعلياً (موثّق أعلاه)، فتبقى تقديرية محلية دائماً.
  // Tavily فقط: نحاول الرصيد الحي أولاً، ونتراجع للتقدير المحلي فقط لو فشل الاستدعاء
  const liveTavily = await fetchTavilyRealUsage()

  return {
    gemini: { ...localEstimate.gemini, isLive: false },
    tavily: liveTavily || { ...localEstimate.tavily, isLive: false },
    serper: { ...localEstimate.serper, isLive: false },
  }
}

