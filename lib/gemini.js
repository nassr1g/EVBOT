async function classifyAddressIntent(userText) {
  const prompt = `
رسالة واتساب فيها اسم بوت (قد يكون "بوت" أو EV أو إيجيما أو إيفي أو ايفي أو egima).
حدد: هل الرسالة موجّهة للبوت مباشرة كمخاطَب (نداء له، سؤال له، طلب منه)، أم مجرد حديث عن البوت لشخص ثالث (وصفه، الشكوى منه لغيره، سرد موقف عنه)؟

أمثلة موجّهة مباشرة (isDirectAddress=true):
"يا بوت شلونك" / "EV اعمل كذا" / "بوت ليش ما رديت" / "اسمع يابوت"

أمثلة حديث عنه لطرف ثالث (isDirectAddress=false):
"البوت هذا خرّب علي الجروب أمس" / "بوت زين لكنه بطيء أحياناً" / "شفتوا شلون رد البوت قبل شوي"

رسالة المستخدم: "${userText}"

أعد JSON فقط.
`

  try {
    const raw0 = await callGemini(prompt, ADDRESS_INTENT_SCHEMA)
    const result = parseJsonSafely(raw0)
    return result.isDirectAddress !== false // افتراضياً true عند أي غموض، لتفادي تجاهل نداء فعلي بالخطأ
  } catch (err) {
    console.error('❌ فشل تصنيف نية المخاطبة:', err.message)
    return true // بحال الفشل، نفترض إنه نداء فعلي بدل ما نتجاهل رسالة قد تكون مهمة
  }
}

