// ─────────────────────────────────────────────
//  رد سياقي عام لأي حالة رفض/خطأ (بدل كل النصوص الثابتة القديمة)
//  reasonKey: معرّف قصير للسبب (يُستخدم للتخزين المؤقت فقط، لا يُرسل للمستخدم كما هو)
//  reasonContext: شرح طبيعي بالعربي للسبب يُعطى لـ Gemini ليصوغه بلغة المستخدم الفعلية
// ─────────────────────────────────────────────

async function generateContextualReply({ chatId, reasonKey, reasonContext, userText = '', skipCache = false }) {
  if (!skipCache) {
    const cached = getCachedRefusal(chatId, reasonKey)
    if (cached) return cached
  }

  const prompt = `
أنت EV، بوت واتساب بشخصية ذكية ومرحة قليلة التكلف. الأمر اللي طلبه المستخدم ما صار للسبب التالي:

السبب: ${reasonContext}
نص المستخدم: "${userText || '(بدون نص)'}"

اكتب جملة واحدة قصيرة جداً تشرح للمستخدم ليش ما صار الأمر، بنفس لغة ولهجة نص المستخدم الأصلي بالضبط
(لو كتب إنجليزي رد إنجليزي، لو عربي رد بنفس لهجته). أسلوب طبيعي كإنسان حقيقي.
لا تعتذر بشكل رسمي، لا تشرح بالتفصيل، جملة عابرة بس.
بدون إيموجي بدون علامات ترقيم كثيرة.

أعد JSON فقط:
{"msg":"..."}
`

  try {
    const raw0 = await callGemini(prompt, ACK_SCHEMA)
    const result = parseJsonSafely(raw0)
    const text = sanitizeCasual(result.msg, 14) || 'صار خطأ'
    if (!skipCache) setCachedRefusal(chatId, reasonKey, text)
    return text
  } catch (err) {
    console.error('❌ فشل توليد رد سياقي حتى بعد المحاولات:', err.message)
    // آخر حل حقيقي بعد استنفاد كل محاولات Gemini — نادر جداً (انقطاع فعلي بالخدمة)
    const fallback = 'صار خطأ تقني، جرب بعدين'
    if (!skipCache) setCachedRefusal(chatId, reasonKey, fallback)
    return fallback
  }
}

