async function classifyConfirmationIntent(userText, candidates = []) {
  // candidates: [{ index, bareId }]
  // ملاحظة: ما فيه مصدر بيانات لأسماء الأشخاص بهذه المرحلة (الذاكرة تخزن أرقام JID فقط لا أسماء عرض)،
  // لذا المطابقة تعتمد على آخر أرقام الرقم أو ترتيب الذكر ("الأول"، "الثاني") فقط، لا على الأسماء.
  const candidatesDescription = candidates
    .map(c => `  ${c.index}) رقمه ينتهي بـ ${c.bareId.slice(-4)}`)
    .join('\n')

  const prompt = `
المستخدم كان عنده سؤال تأكيد معلق من البوت بخصوص شخص يريد تنفيذ أمر عليه (طرد/ترقية/تنزيل إشراف)، وكان فيه أكثر من مرشح محتمل:
${candidatesDescription || '(لا يوجد وصف تفصيلي للمرشحين)'}

رسالة المستخدم الحالية: "${userText}"

حدد:
- إذا كانت الرسالة تأكيد إيجابي عام بدون تحديد مرشح معين (نعم، إي، اطرده، امشي قدام...): intent=confirm و chosenIndex=-1
- إذا حدد المستخدم مرشحاً بترتيب الذكر ("الأول"، "الثاني") أو بجزء من رقمه: intent=confirm و chosenIndex=رقم فهرسه
- إذا كانت رفض أو تراجع (لا، خله، إلغاء، ما أبي...): intent=deny و chosenIndex=-1
- إذا كانت غامضة ولا تحدد شيء واضح: intent=unclear و chosenIndex=-1

أعد JSON فقط.
`

  try {
    const raw0 = await callGemini(prompt, CONFIRMATION_INTENT_SCHEMA)
    const result = parseJsonSafely(raw0)
    return {
      intent: result.intent || 'unclear',
      chosenIndex: Number.isInteger(result.chosenIndex) ? result.chosenIndex : -1,
    }
  } catch (err) {
    console.error('❌ فشل تصنيف نية التأكيد:', err.message)
    return { intent: 'unclear', chosenIndex: -1 }
  }
}

