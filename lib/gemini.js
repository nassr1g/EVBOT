// بوابة معدل إرسال عالمية (على مستوى العملية بالكامل، عبر كل المحادثات معاً) — تحمي حد
// الطلبات بالدقيقة (RPM) الخاص بالمفتاح ككل، بعكس آلية rateLimit.js المنفصلة التي تراقب
// كل محادثة على حدة فقط ولا ترى التراكم عبر عدة محادثات نشطة بنفس اللحظة
let lastGeminiCallAt = 0

async function waitForGlobalRateLimit() {
  const now = Date.now()
  const nextAllowedAt = Math.max(now, lastGeminiCallAt + GLOBAL_GEMINI_MIN_INTERVAL_MS)

  // نحجز الفتحة الزمنية التالية فوراً (قبل الانتظار الفعلي)، حتى لو وصل طلب آخر بنفس
  // اللحظة تقريباً، يرى الوقت المحجوز مسبقاً ويصطف بعده بدل التسابق على نفس القيمة القديمة
  lastGeminiCallAt = nextAllowedAt

  const remaining = nextAllowedAt - now
  if (remaining > 0) {
    await new Promise(r => setTimeout(r, remaining))
  }
}

