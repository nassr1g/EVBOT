function sleep(ms) {
  return new Promise(r => setTimeout(r, ms))
}

function isQuotaExceededError(err) {
  const status = err?.status || err?.code
  const msg = String(err?.message || err || '')
  return status === 429 || /RESOURCE_EXHAUSTED|status: 429/i.test(msg)
}

// إعدادات أمان مخففة إضافياً (تُضيف تخفيف فئة "المضايقة/العنف الخفيف" فوق تخفيف "المحتوى
// الخطير" الافتراضي أعلاه)، تُستخدم للتصنيف الرئيسي وﻻشتقاق استعلام الملصقات تحديداً، لأن
// مصطلحات مثل قتال/ركل/مصارعة/مشاهد أكشن أنمي شائعة جداً بطلبات ملصقات عادية ولا تمثل محتوى
// ضاراً فعلياً، ولا تُستخدم هذي الإعدادات المخففة لأي استدعاء آخر غير هذين الاستخدامين
const RELAXED_ACTION_SAFETY_SETTINGS = [
  { category: 'HARM_CATEGORY_DANGEROUS_CONTENT', threshold: 'BLOCK_ONLY_HIGH' },
  { category: 'HARM_CATEGORY_HARASSMENT', threshold: 'BLOCK_ONLY_HIGH' },
]

async function callGemini(prompt, schema = REPLY_SCHEMA, safetySettings = SAFETY_SETTINGS, temperature = 0.85) {
  let lastErr

  for (let attempt = 1; attempt <= GEMINI_MAX_ATTEMPTS; attempt++) {
    try {
      await waitForGlobalRateLimit()
      const res = await ai.models.generateContent({
        model: MODEL_NAME,
        contents: prompt,
        config: {
          responseMimeType: 'application/json',
          responseSchema: schema,
          temperature,
          safetySettings,
        },
      })
      // نسجل الاستهلاك فقط بعد نجاح فعلي للطلب — طلب فشل بالكامل بعد كل المحاولات
      // لا يُحتسب هنا (Google لا تحتسبه أيضاً على أنه استهلاك حصة ناجح)
      usageTracker.recordUsage('gemini')
      return res.text
    } catch (err) {
      lastErr = err
      console.error(`❌ Gemini Error (محاولة ${attempt}/${GEMINI_MAX_ATTEMPTS}):`, err?.message || String(err))

      if (isQuotaExceededError(err)) {
        // خطأ حصة مستنفدة سيفشل بنفس الطريقة تماماً في كل محاولة — إعادة المحاولة
        // فورية عديمة الجدوى وتهدر طلبات إضافية من حصة مستنفدة أصلاً، فنتوقف فوراً
        console.error('⚠️ الحصة مستنفدة (429) — إيقاف إعادة المحاولة فوراً بدل هدر محاولات إضافية')
        break
      }

      if (attempt < GEMINI_MAX_ATTEMPTS) {
        await sleep(GEMINI_RETRY_DELAY_MS * attempt)
      }
    }
  }


  throw lastErr
}

function parseJsonSafely(raw0) {
  const raw = cleanDecorations(raw0 || '')
  const jsonMatch = raw.match(/\{[\s\S]*\}/)
  return JSON.parse(jsonMatch ? jsonMatch[0] : raw)
}

